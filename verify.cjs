const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(__dirname + '/index.html', 'utf8');
const scripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(m => m[1]).filter(s => s.trim());
scripts.forEach((s, i) => new vm.Script(s, {filename:'inline-' + i}));
function extract(name){
  const start = html.indexOf('function ' + name + '(');
  assert(start >= 0, name + ' exists');
  const next = html.indexOf('\nfunction ', start + 1);
  return html.slice(start, next);
}
const context = vm.createContext({URL, Intl, Date, Object, String});
['escapeHtml','escapeAttr','safeExternalUrl','todayISO'].forEach(name => vm.runInContext(extract(name), context));
assert.equal(context.todayISO(new Date('2026-10-03T17:00:00Z')), '2026-10-04');
assert.equal(context.todayISO(new Date('2026-10-03T16:59:59Z')), '2026-10-03');
assert.equal(context.todayISO(new Date('2028-02-28T17:00:00Z')), '2028-02-29');
assert.equal(context.escapeHtml(0), '0');
assert.equal(context.escapeAttr('"<&\''), '&quot;&lt;&amp;&#39;');
['javascript:alert(1)','data:text/html,hello','file:///secret','not a url'].forEach(url => assert.equal(context.safeExternalUrl(url), ''));
assert.equal(context.safeExternalUrl('https://example.com/?a=1&b=2'), 'https://example.com/?a=1&b=2');
assert.equal(context.safeExternalUrl('http://example.com'), 'http://example.com/');
const cardSource = extract('buildCard');
assert(!cardSource.includes('onclick="copyText('), 'Card copy values are not executable inline JS');
assert(cardSource.includes('data-card-copy="desc"'));
assert(html.includes('const useLatestDataExport = !parsed;'), 'Existing saved data takes precedence');
assert(html.includes('pctGetSheetUrl();'), 'Dashboard and CRM URL are reconciled on load');
assert(html.includes('PCT_RETIRED_WEB_APP_URL'), 'Only the retired deployment is migrated');
const uiReminder = 'หมายเหตุ : หากมี Wallpaper สิ่งกีดขวางบริเวณติดตั้ง แนะนำให้ลูกค้าเคลียร์พื้นที่ให้เรียบร้อย หากเกิดความเสียหายจะไม่อยู่ในการดูแลของทางศูนย์บริการ';
assert.equal(html.split(uiReminder).length - 1, 1, 'Reminder exists only in the form markup');
assert(html.includes('class="crm-installation-reminder" style="color:#dc2626;'), 'Reminder is red');
const templateContext = vm.createContext({crmQuestionsFor:()=>['ข้อหนึ่ง','ข้อสอง','ข้อสาม'],toDMY:()=>'',CRM_REMINDER_TEXT:'Existing reminder'});
vm.runInContext(extract('formatAppointmentTimeForPost'), templateContext);
const templateStart = html.indexOf('function crmBuildColumnO(');
const templateEnd = html.indexOf('\nconst CRM_CUSTOMER_NOTE_TEXT_AIR',templateStart);
vm.runInContext(html.slice(templateStart,templateEnd), templateContext);
const copied = templateContext.crmBuildColumnO({productType:'air',answers:[],airFloor:'2',airOutdoor:'ภายนอก',airIndoor:'ภายใน'});
assert(!copied.includes(uiReminder), 'Copied template excludes UI-only reminder');
assert(copied.includes('- ชั้นที่ติดตั้ง: 2'), 'Existing answers remain in copied template');
for(const productType of ['air','washer','repair']){
 const output=templateContext.crmBuildColumnO({productType,so:'SO-DEMO',model:'Model demo',customerName:'Customer demo',answers:[]});
 assert(output.startsWith('Service Order : SO-DEMO\nType : Model demo\nCustomer : Customer demo'),productType+' places model immediately after SO');
 assert.equal(output.match(/^Type :/gm).length,1);
}
vm.runInContext(extract('patchBuildText'),templateContext);
assert(templateContext.patchBuildText({fields:{so:'SO-DEMO',type:'Model demo'},questions:[]}).startsWith('Service Order : SO-DEMO\nType : Model demo\nCustomer :'));
vm.runInContext(extract('customerTemplateModelFirst'),templateContext);
const oldTemplate='Service Order : SO-DEMO\nCustomer : Name\nExpected Time : 10.00\nType : Model demo\nNoted : Note';
const updated=templateContext.customerTemplateModelFirst(oldTemplate);
assert.equal(updated,'Service Order : SO-DEMO\nType : Model demo\nCustomer : Name\nExpected Time : 10.00\nNoted : Note');
assert.equal(templateContext.customerTemplateModelFirst(updated),updated);
const questionStart=html.indexOf('const CRM_SURVEY_QUESTIONS_AIR');
vm.runInContext(html.slice(questionStart,html.indexOf('\nfunction toDMY',questionStart)),templateContext);
const fridge={productType:'fridge',model:'Refrigerator demo',so:'SO-DEMO',answers:['Grounded outlet','80 x 70 x 190 cm','Door 90 cm','Saturday allowed','Customer present']};
assert.equal(templateContext.crmQuestionsFor('fridge').length,5);
const fridgeText=templateContext.crmBuildColumnO(JSON.parse(JSON.stringify(fridge)));
assert(fridgeText.startsWith('Service Order : SO-DEMO\nType : Refrigerator demo\nCustomer :'));
assert(fridgeText.includes('3.จุดติดตั้งผ่านประตูหรือไม่'));
assert.equal(templateContext.crmQuestionsFor('fridge')[2],'จุดติดตั้งผ่านประตูหรือไม่ ขนาดกว้าง ยาว สูงเท่าไหร่ หากขนาดไม่พอ รบกวนลูกค้าเตรียมพื้นที่ให้ทีมช่างสามารถนำสินค้าเข้าไปติดตั้งได้');
for(const answer of fridge.answers) assert(fridgeText.includes(answer));
assert(fridgeText.includes('ห้ามเลื่อนนัด') && fridgeText.includes('**หากมีการเลื่อนวันหรือยกเลิก'));
assert(!fridgeText.includes('คอยล์ร้อน'));
templateContext.CRM_LINE_LANGUAGES={th:{},en:{},zh:{}};
vm.runInContext(extract('crmBuildLineMessage'),templateContext);
for(const language of ['th','en','zh']){
 const message=templateContext.crmBuildLineMessage(fridge,language);
 assert(message.includes('Refrigerator demo'));
 assert(!/คอยล์|Indoor and outdoor|室内机/.test(message));
}
assert(html.includes('<option value="fridge"'));
console.log('PASS: ' + scripts.length + ' inline scripts parse; original tests + 4 reminder assertions pass.');
console.log('Browser smoke tests are separate; no production backend writes performed.');
